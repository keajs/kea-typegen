// Only completed declarations and the locations used by the source editor
// leave the checker process. Keep the visitor's mutable model private to Go.
type generated struct {
	Name, File, ImportedFrom, Declaration  string
	End                                    int
	BuilderArray, HasPath, SharedListeners bool
	Steps                                  []step
	Path, TypeArgs, Values                 []string
	Imports                                []importedName
	Annotations                            []annotation
}

func (l *logic) generate(inline, metaArgument bool) generated {
	out := generated{Name: l.Name, File: l.File, ImportedFrom: l.ImportedFrom, End: l.End, BuilderArray: l.BuilderArray, HasPath: l.HasPath, Steps: l.Steps, TypeArgs: l.TypeArgs, Path: l.Path, Imports: l.Imports, Annotations: l.Annotations, SharedListeners: len(l.SharedListeners) > 0}
	values := uniqueValues(slices.Concat(l.Reducers, l.Selectors))
	for _, v := range values {
		out.Values = append(out.Values, v.Name)
	}
	if inline {
		out.Declaration = l.inlineDeclaration(values, metaArgument)
	} else {
		out.Declaration = l.externalDeclaration(values)
	}
	return out
}

const marker = "// Generated by kea-typegen. Update if you're an agent, ignore if you're human.\n"

func quoted(s string) string { b, _ := json.Marshal(s); return string(b) }
func propName(name string) string {
	if scanner.IsIdentifierText(name, core.LanguageVariantStandard) {
		return name
	}
	return quoted(name)
}

func field(name, typ string) string {
	if typ == "" {
		return propName(name) + ";"
	}
	return propName(name) + ": " + typ + ";"
}

func object(members []string) string {
	if len(members) == 0 {
		return "{}"
	}
	return "{\n" + strings.Join(members, "\n") + "\n}"
}

func signature(params []parameter, typ string) string {
	args := make([]string, len(params))
	for i, p := range params {
		name := p.Name
		if p.Optional {
			name += "?"
		}
		args[i] = name + ": " + p.Type
	}
	return "(" + strings.Join(args, ", ") + ") => " + typ
}

func uniqueValues(values []value) []value {
	index := map[string]int{}
	out := []value{}
	for _, v := range values {
		if i, ok := index[v.Name]; ok {
			t := strings.TrimSpace(v.Type)
			// A duplicate with an uninformative type must preserve the earlier inference.
			if inner, ok := strings.CutPrefix(t, "Promise<"); ok {
				t = strings.TrimSpace(strings.TrimSuffix(inner, ">"))
			}
			if t != "" && t != "any" && t != "unknown" && t != "{}" && t != "Promise" {
				out[i] = v
			}
		} else {
			index[v.Name] = len(out)
			out = append(out, v)
		}
	}
	return out
}

func (l *logic) selectorMeta() string {
	var ms []string
	for _, s := range l.Selectors {
		if len(s.Inputs) > 0 {
			ms = append(ms, field(s.Name, signature(s.Inputs, s.Type)))
		}
	}
	return object(ms)
}

func (l *logic) externalActionsType() string {
	var ms []string
	for _, a := range l.ExtraActions {
		ms = append(ms, quoted(a.Name)+": "+a.Type+";")
	}
	return object(ms)
}

func (l *logic) sharedListenersType() string {
	var ms []string
	for _, s := range l.SharedListeners {
		ms = append(ms, quoted(s.Name)+": (payload: "+s.Payload+", breakpoint: BreakPointFunction, action: "+s.Action+", previousState: any) => void | Promise<void>;")
	}
	return object(ms)
}

func (l *logic) internalFields() []string {
	var fields []string
	for _, name := range slices.Sorted(maps.Keys(l.LogicFieldMembers)) {
		var members []string
		for _, member := range uniqueValues(l.LogicFieldMembers[name]) {
			members = append(members, field(member.Name, member.Type))
		}
		fields = append(fields, field(name, object(members)))
	}
	if t := l.selectorMeta(); t != "{}" {
		fields = append(fields, field("__keaTypeGenInternalSelectorTypes", t))
	}
	if t := l.externalActionsType(); t != "{}" {
		fields = append(fields, field("__keaTypeGenInternalReducerActions", t))
	}
	return fields
}

func sortedFields(values []value) []string {
	values = slices.Clone(values)
	slices.SortStableFunc(values, func(a, b value) int {
		if (a.Source == "") != (b.Source == "") {
			if a.Source != "" {
				return -1
			}
			return 1
		}
		if d := cmp.Compare(a.Source, b.Source); d != 0 {
			return d
		}
		return cmp.Compare(a.Name, b.Name)
	})
	var ms []string
	for _, v := range values {
		m := field(v.Name, v.Type)
		if v.Source != "" {
			m += " // " + strings.ReplaceAll(strings.ReplaceAll(v.Source, "\r", " "), "\n", " ")
		}
		ms = append(ms, m)
	}
	return ms
}

func (l *logic) inlineDeclaration(values []value, metaArgument bool) string {
	var blocks, args []string
	section := func(suffix, body string) {
		if body == "{}" {
			args = append(args, body)
			return
		}
		name := l.Name + suffix
		blocks = append(blocks, marker+"export interface "+name+" "+body)
		args = append(args, name)
	}
	section("Values", object(sortedFields(values)))
	var actions []value
	for _, a := range l.Actions {
		actions = append(actions, value{Name: a.Name, Type: signature(a.Params, a.Type), Source: a.Source})
	}
	section("Actions", object(sortedFields(actions)))
	if l.Props != "" {
		if l.PropsLiteral {
			section("Props", l.Props)
		} else {
			args = append(args, l.Props)
		}
	}
	var meta []string
	if l.Key != "" {
		meta = append(meta, field("key", l.Key))
	}
	if len(l.SharedListeners) > 0 {
		meta = append(meta, field("sharedListeners", l.sharedListenersType()))
	}
	meta = append(meta, l.internalFields()...)
	suffix := ""
	if len(meta) > 0 {
		if l.Props == "" {
			args = append(args, "Record<string, any>")
		}
		section("Meta", object(meta))
		if !metaArgument {
			suffix = " & " + args[len(args)-1]
			args = args[:len(args)-1]
		}
	}
	alias := "export type " + l.Name + "Type = MakeLogicType<" + strings.Join(args, ", ") + ">" + suffix + ";"
	if len(blocks) == 0 {
		alias = marker + alias
	}
	return strings.Join(append(blocks, alias), "\n\n")
}

func (l *logic) externalDeclaration(values []value) string {
	groups := map[string][]string{}
	for _, a := range l.Actions {
		actionType := strings.TrimPrefix(upperLetter.ReplaceAllStringFunc(a.Name, spaceLetter), " ") + " (" + strings.Join(l.Path, ".") + ")"
		groups["actionCreators"] = append(groups["actionCreators"], field(a.Name, signature(a.Params, "({ type: "+quoted(actionType)+"; payload: "+a.Type+"; })")))
		groups["actionKeys"] = append(groups["actionKeys"], quoted(actionType)+": "+quoted(a.Name)+";")
		groups["actionTypes"] = append(groups["actionTypes"], field(a.Name, quoted(actionType)))
		groups["actions"] = append(groups["actions"], field(a.Name, signature(a.Params, "void")))
		groups["asyncActions"] = append(groups["asyncActions"], field(a.Name, signature(a.Params, "Promise<any>")))
	}
	for _, r := range uniqueValues(l.Reducers) {
		groups["defaults"] = append(groups["defaults"], field(r.Name, r.Type))
		groups["reducers"] = append(groups["reducers"], field(r.Name, "(state: "+cmp.Or(r.Type, "any")+", action: any, fullState: any) => "+cmp.Or(r.Type, "any")))
	}
	for _, v := range values {
		groups["values"] = append(groups["values"], field(v.Name, v.Type))
		groups["selectors"] = append(groups["selectors"], field(v.Name, "(state: any, props?: any) => "+cmp.Or(v.Type, "any")))
	}
	for _, e := range l.Events {
		groups["events"] = append(groups["events"], field(e, "() => void"))
	}
	for _, s := range l.Listeners {
		groups["listeners"] = append(groups["listeners"], quoted(s.Name)+": ((action: "+s.Action+", previousState: any) => void | Promise<void>)[];")
	}
	var ms []string
	for _, name := range []string{"actionCreators", "actionKeys", "actionTypes", "actions", "asyncActions", "defaults", "events"} {
		ms = append(ms, field(name, object(groups[name])))
	}
	var parts []string
	for _, part := range l.Path {
		parts = append(parts, quoted(part))
	}
	ms = append(ms, field("key", cmp.Or(l.Key, "undefined")), field("listeners", object(groups["listeners"])),
		field("path", "["+strings.Join(parts, ", ")+"]"), field("pathString", quoted(strings.Join(l.Path, "."))),
		field("props", cmp.Or(l.Props, "Record<string, unknown>")),
		field("reducer", "(state: any, action: any, fullState: any) => "+object(groups["defaults"])),
		field("reducers", object(groups["reducers"])), field("selector", "(state: any) => "+object(groups["defaults"])),
		field("selectors", object(groups["selectors"])), field("sharedListeners", l.sharedListenersType()), field("values", object(groups["values"])),
		field("_isKea", "true"), field("_isKeaWithKey", strconv.FormatBool(l.Key != "")))
	return "export interface " + l.Name + "Type extends Logic " + object(append(ms, l.internalFields()...))
}

func (v *visitor) inline(logics []*logic) bool {
	name := v.file.FileName().AsString()
	if !strings.HasSuffix(name, ".ts") && !strings.HasSuffix(name, ".tsx") && !strings.HasSuffix(name, ".mts") && !strings.HasSuffix(name, ".cts") {
		return false
	}
	if v.opts.Inline {
		return true
	}
	for _, dir := range v.opts.InlinePaths {
		if !filepath.IsAbs(dir) {
			dir = filepath.Join(v.opts.RootPath, dir)
		}
		rel, err := filepath.Rel(dir, name)
		if err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
			return true
		}
	}
	for _, l := range logics {
		for _, s := range v.file.Statements.Nodes {
			if (ast.IsInterfaceDeclaration(s) || ast.IsTypeAliasDeclaration(s)) && s.Name().Text() == l.Name+"Type" && v.managedDeclaration(s, l.Name) {
				return true
			}
		}
	}
	return false
}
